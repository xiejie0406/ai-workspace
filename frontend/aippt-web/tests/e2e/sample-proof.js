async (page) => {
  const dialog = page.getByRole('dialog', { name: '主题与版式样例', exact: true })
  await dialog.getByRole('button', { name: '深蓝科技', exact: true }).click()
  await dialog.getByRole('button', { name: '5 · 图表页', exact: true }).click()
  await dialog.getByText('分季度收入构成', { exact: true }).waitFor()
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/09-主题内样例与原图表.png' })
  if (await dialog.getByRole('button', { name: '导出样例 PPTX', exact: true }).isEnabled()) throw new Error('未检查样例质量就可导出')
  await dialog.getByRole('button', { name: '检查样例质量', exact: true }).click()
  await dialog.getByText('检查完成，1 项警告', { exact: true }).waitFor()
  if (await dialog.getByRole('button', { name: '导出样例 PPTX', exact: true }).isEnabled()) throw new Error('未确认样例警告就可导出')
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/10-样例异步质量警告.png' })
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '导出样例 PPTX', exact: true }).click()
  await dialog.getByText('第 5 页 · chart · 技术夹具原生图表回读失败', { exact: true }).waitFor()
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/11-样例回读失败定位.png' })
  const stateBefore = await page.evaluate(() => window.aipptFixtureControl({}))
  if (stateBefore.requests.some((request) => request.path.endsWith('/download'))) throw new Error('回读失败仍下载了样例')
  await dialog.getByRole('button', { name: '导出样例 PPTX', exact: true }).click()
  await dialog.getByText('已开始下载', { exact: true }).waitFor()
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/12-样例终态新尝试下载.png' })
  const state = await page.evaluate(() => window.aipptFixtureControl({}))
  const exports = state.requests.filter((request) => request.path === '/aippt/design/sample-deck/exports')
  if (exports.length !== 2 || exports[0].key === exports[1].key) throw new Error('明确失败终态后没有新幂等键')
  if (exports.some((request) => { const body = JSON.parse(request.body); return body.theme_id !== 'midnight' || body.acknowledge_warnings !== true })) throw new Error('未向样例导出传所选主题与实际警告确认')
  const downloads = state.requests.filter((request) => request.path.endsWith('/download'))
  if (downloads.length !== 1 || downloads[0].path !== '/aippt/exports/sample-export-2/download') throw new Error('下载未指向第二个正式ready夹具制品')
  await dialog.getByRole('button', { name: '关闭', exact: true }).first().click()
  await page.locator('input[type=color]').first().fill('#E3EDF7')
  for (let i = 0; i < 80; i++) { if ((await page.evaluate(() => window.aipptFixtureControl({}))).project.theme_revision === 4) break; await page.waitForTimeout(20) }
  const final = await page.evaluate(() => window.aipptFixtureControl({}))
  if (final.project.theme_revision !== 4) throw new Error('主题320ms保存没有推进正式版本')
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/13-原主题微调即时预览.png' })
  await page.getByRole('button', { name: '放大', exact: true }).click(); await page.getByRole('button', { name: '放大', exact: true }).click(); await page.getByRole('button', { name: '放大', exact: true }).click()
  if (await page.getByRole('button', { name: '放大', exact: true }).isEnabled()) throw new Error('原160%上限被改变')
  await page.getByText('160%', { exact: true }).waitFor()
  await page.screenshot({ path: '../../output/playwright/aippt-react-entry/14-原五档160缩放.png' })
  return { scope: '仅技术fixture；下载字节不是有效PPTX', exports, downloads, qualityAndTasks: state.requests.filter((request) => request.path.includes('/tasks/') || request.path.includes('/sample-deck/issues')), themeWrites: final.requests.filter((request) => request.path.endsWith('/theme')) }
}
