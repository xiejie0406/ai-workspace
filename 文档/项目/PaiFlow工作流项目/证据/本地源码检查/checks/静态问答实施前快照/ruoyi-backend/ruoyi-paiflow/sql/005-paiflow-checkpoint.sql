CREATE TABLE paiflow_run_checkpoint (
  id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  run_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lease_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  attempt INT NOT NULL,
  node_id VARCHAR(255) NOT NULL,
  iteration_id VARCHAR(255) NULL,
  iteration_key VARCHAR(255) NOT NULL,
  ordinal INT NOT NULL,
  need_reply TINYINT NOT NULL,
  state VARCHAR(16) NOT NULL,
  request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  question_json LONGTEXT NOT NULL,
  resume_data_json LONGTEXT NULL,
  reply_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  reply_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  consume_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  consume_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  revision BIGINT NOT NULL DEFAULT 0,
  deadline DATETIME(6) NOT NULL,
  create_time DATETIME(6) NOT NULL,
  update_time DATETIME(6) NOT NULL,
  PRIMARY KEY(id),
  UNIQUE KEY uk_checkpoint_request(run_id,attempt,request_key),
  UNIQUE KEY uk_checkpoint_position(run_id,attempt,node_id,iteration_key,ordinal),
  KEY idx_checkpoint_end(state,deadline),
  CONSTRAINT ck_checkpoint_attempt CHECK(attempt>=1),
  CONSTRAINT ck_checkpoint_ordinal CHECK(ordinal BETWEEN 1 AND 5),
  CONSTRAINT ck_checkpoint_required CHECK(need_reply IN(0,1)),
  CONSTRAINT ck_checkpoint_state CHECK(state IN('WAITING','RESUMED','CONSUMED','EXPIRED','CANCELLED')),
  CONSTRAINT ck_checkpoint_revision CHECK(revision>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
