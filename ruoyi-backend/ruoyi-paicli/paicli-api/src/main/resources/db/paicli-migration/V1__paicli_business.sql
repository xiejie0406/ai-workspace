-- PaiCLI中心MySQL8正式账本。显式迁移CLI执行；应用启动只核对，不自动迁移。

-- owner_id引用平台稳定用户ID；不创建跨业务外键、JOIN或事务。

-- 类型化JSON由Java业务服务验证。敏感凭证只保存hash或AES-GCM密文。

CREATE TABLE pc_workspace (
  id BIGINT NOT NULL AUTO_INCREMENT,
  workspace_id BIGINT NULL,
  owner_id BIGINT NULL,
  parent_id BIGINT NULL,
  session_id BIGINT NULL,
  runner_id BIGINT NULL,
  kind VARCHAR(64) NOT NULL,
  state VARCHAR(40) NOT NULL,
  unique_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
  content_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  payload JSON NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  sequence_number BIGINT NOT NULL DEFAULT 0,
  fencing_token BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(3) NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL,
  expires_at TIMESTAMP(3) NULL,
  PRIMARY KEY(id),
  UNIQUE KEY uq_pc_workspace_key(unique_key),
  KEY ix_pc_workspace_scope(workspace_id,owner_id,state,id),
  KEY ix_pc_workspace_parent(parent_id,state),
  KEY ix_pc_workspace_session(session_id,sequence_number),
  KEY ix_pc_workspace_expiry(state,expires_at),
  KEY ix_pc_workspace_runner(runner_id,state)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

